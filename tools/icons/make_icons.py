"""Makes the launcher icons for the Heartnet Apps apps: the orange gear from the Heartnet Apps logo on white,
with a small white-cut glyph for each app in the middle. Run it from anywhere:

    python make_icons.py

It writes Android resources into each app's android/res folder and a preview.png to look at.
"""
import math
import os
import shutil

HERE = os.path.dirname(os.path.abspath(__file__))
ORANGE = "#FC5700"  # sampled from the logo
CENTER = 54.0       # the adaptive icon canvas is 108 x 108
TEETH = 24
R_TIP, R_ROOT, R_HOLE = 31.5, 28.0, 21.5  # inside the 66 dp safe zone (radius 33)

GLYPHS = {
    # (list of polygons, list of circles (x, y, r)) in the 108 canvas, inside the hole
    "gallery": (
        [[(41.5, 64), (49.5, 51), (55, 58), (58.5, 53.5), (66.5, 64)]],
        [(60, 45.5, 3.2)],
    ),
    "files": (
        [[(41.5, 50.5), (49.5, 50.5), (52.5, 54), (66.5, 54), (66.5, 66), (41.5, 66)]],
        [],
    ),
    "home": (
        [[(41, 55.5), (54, 44.5), (67, 55.5), (63.5, 55.5), (63.5, 66.5), (56.5, 66.5), (56.5, 59.5), (51.5, 59.5), (51.5, 66.5), (44.5, 66.5), (44.5, 55.5)]],
        [],
    ),
    "notes": (
        [[(43, 46), (65, 46), (65, 49.5), (43, 49.5)], [(43, 52.5), (65, 52.5), (65, 56), (43, 56)], [(43, 59), (57, 59), (57, 62.5), (43, 62.5)]],
        [],
    ),
}


def pol(r, deg):
    a = math.radians(deg)
    return (CENTER + r * math.cos(a), CENTER + r * math.sin(a))


def gear_outline():
    pts = []
    pitch = 360.0 / TEETH
    for k in range(TEETH):
        a = k * pitch - 90
        pts += [pol(R_ROOT, a - pitch * 0.34), pol(R_TIP, a - pitch * 0.22), pol(R_TIP, a + pitch * 0.22), pol(R_ROOT, a + pitch * 0.34)]
    return pts


def path_data(points):
    return "M" + " L".join(f"{x:.2f},{y:.2f}" for x, y in points) + " Z"


def circle_path(cx, cy, r):
    return f"M{cx - r:.2f},{cy:.2f} a{r:.2f},{r:.2f} 0 1,0 {2 * r:.2f},0 a{r:.2f},{r:.2f} 0 1,0 {-2 * r:.2f},0 Z"


def foreground_xml(name):
    polys, circles = GLYPHS[name]
    ring = path_data(gear_outline()) + " " + circle_path(CENTER, CENTER, R_HOLE)
    glyph = " ".join(path_data(p) for p in polys) + " " + " ".join(circle_path(*c) for c in circles)
    return f'''<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by branding/make_icons.py: the Heartnet Apps gear with this app's mark inside. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="108dp"
    android:height="108dp"
    android:viewportWidth="108"
    android:viewportHeight="108">
    <path
        android:fillColor="{ORANGE}"
        android:fillType="evenOdd"
        android:pathData="{ring}" />
    <path
        android:fillColor="{ORANGE}"
        android:pathData="{glyph.strip()}" />
</vector>
'''


ADAPTIVE = '''<?xml version="1.0" encoding="utf-8"?>
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@color/ic_background" />
    <foreground android:drawable="@drawable/ic_foreground" />
    <monochrome android:drawable="@drawable/ic_foreground" />
</adaptive-icon>
'''

COLORS = '''<?xml version="1.0" encoding="utf-8"?>
<resources>
    <color name="ic_background">#FFFFFF</color>
</resources>
'''


def write(path, text):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)


def make_app(name, app_dir):
    res = os.path.join(app_dir, "android", "res")
    shutil.rmtree(res, ignore_errors=True)
    write(os.path.join(res, "drawable", "ic_foreground.xml"), foreground_xml(name))
    write(os.path.join(res, "mipmap-anydpi-v26", "ic_launcher.xml"), ADAPTIVE)
    write(os.path.join(res, "mipmap-anydpi-v26", "ic_launcher_round.xml"), ADAPTIVE)
    write(os.path.join(res, "values", "colors.xml"), COLORS)


def preview():
    from PIL import Image, ImageDraw

    scale, size = 4, 108
    tiles = []
    for name in GLYPHS:
        img = Image.new("RGBA", (size * scale, size * scale), (255, 255, 255, 255))
        d = ImageDraw.Draw(img)
        s = lambda pts: [(x * scale, y * scale) for x, y in pts]
        # even-odd ring: gear polygon, then the hole punched back to white
        d.polygon(s(gear_outline()), fill=ORANGE)
        d.ellipse([(CENTER - R_HOLE) * scale, (CENTER - R_HOLE) * scale, (CENTER + R_HOLE) * scale, (CENTER + R_HOLE) * scale], fill="white")
        polys, circles = GLYPHS[name]
        for p in polys:
            d.polygon(s(p), fill=ORANGE)
        for cx, cy, r in circles:
            d.ellipse([(cx - r) * scale, (cy - r) * scale, (cx + r) * scale, (cy + r) * scale], fill=ORANGE)
        tiles.append(img)
    sheet = Image.new("RGB", (len(tiles) * 2 * size * scale + 60, size * scale + 40), (24, 24, 30))
    x = 20
    for img in tiles:
        # as the launcher shows it: the middle 72 dp, cut to a circle, then a squircle
        crop = img.crop((18 * scale, 18 * scale, 90 * scale, 90 * scale))
        for shape in ("circle", "round"):
            mask = Image.new("L", crop.size, 0)
            md = ImageDraw.Draw(mask)
            if shape == "circle":
                md.ellipse([0, 0, crop.size[0] - 1, crop.size[1] - 1], fill=255)
            else:
                md.rounded_rectangle([0, 0, crop.size[0] - 1, crop.size[1] - 1], radius=crop.size[0] // 4, fill=255)
            sheet.paste(crop, (x, 20), mask)
            x += crop.size[0] + 10
    sheet.save(os.path.join(HERE, "preview.png"))


if __name__ == "__main__":
    root = os.path.join(os.path.dirname(os.path.dirname(HERE)), "apps")
    make_app("gallery", os.path.join(root, "gallery"))
    make_app("files", os.path.join(root, "files"))
    make_app("home", os.path.join(root, "home"))
    make_app("notes", os.path.join(root, "notes"))
    preview()
    print("icons written; preview at", os.path.join(HERE, "preview.png"))
